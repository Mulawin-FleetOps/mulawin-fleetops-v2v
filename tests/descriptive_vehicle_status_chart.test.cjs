'use strict';
const fs=require('node:fs');
const assert=require('node:assert/strict');
const source=fs.readFileSync('backend/Modules/General/Analytics.php','utf8');
for(const type of ['Wing Van','Car Carrier','Container'])assert.ok(source.includes("'"+type+"'"),'Missing vehicle type '+type);
assert.match(source,/Trips by Vehicle Type and Status/);
assert.match(source,/GROUP BY t\.truck_type, t\.status/);
assert.match(source,/DATE\(t\.scheduled_at\) BETWEEN \? AND \?/);
assert.match(source,/\$w\s+GROUP BY t\.truck_type, t\.status/);
assert.match(source,/\$vehicleStatusCounts\s*=\s*array_fill_keys/);
assert.match(source,/\$vehicleStatusDatasets/);
assert.match(source,/\$category = 'Other'/);
assert.match(source,/\['Dispatched', 'In Transit'\]/);
assert.match(source,/\['On Hold - Incident Reported'\]/);
assert.match(source,/\['type' => 'bar', 'title' => 'Trips by Vehicle Type and Status'/);
assert.match(source,/'stacked' => true/);
assert.match(source,/A redispatch remains one trip, not a new trip/);
assert.ok(!source.includes("'title' => 'Trips by truck type'"),'Redundant donut must be removed');
assert.ok(source.includes("['Delivered units (car carrier)', 'units'"),'Retain the delivered units KPI');
const admin=fs.readFileSync('public/assets/js/modules/administration/oversight.js','utf8');
assert.match(admin,/const vehicleStatusChart = \(trips\.charts \|\| \[\]\)\.find\(c => c\.title === 'Trips by Vehicle Type and Status'\)/);
assert.match(admin,/plot\('Trips by Vehicle Type and Status', 'stack'/);
assert.match(admin,/A rescheduled trip is counted once/);
assert.ok(!admin.includes("plot('Delivered units by client · car carrier'"),'Old Admin Descriptive Trip Operations chart must be removed');
assert.ok(admin.includes("cardsOf(trips,['Total trips','Completed trips','Cancelled trips','Trips for reschedule','Delivered units (car carrier)','Incidents'])"),'Keep delivered units required KPI in Admin Descriptive Analytics');
console.log('PASS: Admin Descriptive Trip Operations uses new stacked vehicle status chart and retains Delivered Units KPI');
const oversight=fs.readFileSync('backend/Modules/Administration/Oversight.php','utf8');
assert.match(oversight,/\$data\['generalBudgetUtilization'\]/);
assert.match(oversight,/category='General' AND status='Active'/);
assert.match(oversight,/CURRENT_DATE\(\) BETWEEN period_start AND period_end/);
assert.match(oversight,/amount-reserved_amount-spent_amount AS available/);
assert.ok(!admin.includes("plot('Client collections by week'"),'Old Admin Finance chart must be removed');
assert.match(admin,/plot\('General Budget Utilization','stack'/);
for(const state of ['Spent','Reserved','Available'])assert.ok(admin.includes("label:'"+state+"'"),'Missing budget allocation state '+state);
assert.match(admin,/No currently effective, Admin-approved General Budget/);
assert.match(admin,/not a historical amount filtered by the selected report dates/);
console.log('PASS: Admin Finance Descriptive General Budget utilization, active-only source, clear empty state');
console.log('PASS: Descriptive vehicle type/status chart contract, filters, statuses, and KPI preservation');
